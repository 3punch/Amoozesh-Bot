FALLBACK_MESSAGE = (
    "متأسفم، الان نتوانستم پاسخ را آماده کنم. لطفاً سوال را کوتاه‌تر و با نام دقیق درس یا استاد بپرسید."
)

GREETING = (
    "سلام 👋 من دستیار انتخاب واحد هستم؛ از داده‌های همین ترم نتیجه می‌گیرم.\n"
    "نمونه‌ی پرسش‌ها:\n"
    "• آیا درس بهینه سازی خطی برای ورودی ۱۴۰۴ مجاز است؟\n"
    "• استاد آذر ابوالقاسمی چطور است؟\n"
    "• ساختمان داده و الگوریتم‌ها با همامی چه زمانی ارائه شده؟"
)


def build_messages(query: str, context: str) -> list[dict]:
    user = query
    # Qwen3 در حالت فکر نکردن باید /no_think ببیند، وگرنه استدلال طولانی می‌نویسد
    if llm.is_thinking_model() and not llm.THINK:
        user = f"{query}\n/no_think"
    return [
        {"role": "system", "content": SYSTEM_PROMPT.format(context=context)},
        {"role": "user", "content": user},
    ]
