def build_analysis_messages(query: str, context: str) -> list[dict]:
    """پیام‌های حالت «تحلیل مدل»: متن کامل + درخواست فهم و قضاوت."""
    user = query
    if llm.is_thinking_model() and not llm.THINK:
        user = f"{query}\n/no_think"
    return [
        {"role": "system", "content": ANALYSIS_PROMPT.format(context=context)},
        {"role": "user", "content": user},
    ]
